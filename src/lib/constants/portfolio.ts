/**
 * 수치의 출처. 화면에서는 기호와 뜻을 함께 보여준다.
 * 실측 ●: 개선 전후를 직접 쟀다 / 인용 ○: 당시 커밋·MR에 남은 값 / 계산 ◐: 모델로 산출한 값
 * 구조 ■: 측정값이 아니라 코드 구조가 보장하는 성질 / 못 잼 ✕: 재지 못했고 이유를 적었다
 */
export type MetricGrade = '실측' | '인용' | '계산' | '구조' | '못 잼';

export interface Metric {
  /** 무엇을 잰 값인지. 예: "메인 스레드 점유" */
  label: string;
  /** 개선 전 값. 없으면 개선 후 값만 보여준다 */
  before?: string;
  after: string;
  grade: MetricGrade;
  /** 등급 근거나 조건 한 줄 */
  note?: string;
}

/** 캡처 이미지 또는 무음 반복 영상 */
export interface Media {
  kind: 'image' | 'video';
  src: string;
  /** 이미지의 alt이자 영상의 접근성 레이블 */
  alt: string;
  /** 원본 해상도. 로드 전에 자리를 잡아 레이아웃이 밀리지 않게 한다 */
  width: number;
  height: number;
}

/** mermaid로 그린 도표. 테마 지시문은 DiagramFigure가 붙이므로 code에 넣지 않는다 */
export interface DiagramVisual {
  kind: 'diagram';
  code: string;
  caption: string;
}

/** 이미지. media가 없으면 채워야 할 캡처를 description으로 설명하는 이미지 자리로 렌더링한다 */
export interface ImageVisual {
  kind: 'image';
  /** 이미지 자리를 가리키는 식별자. 캡처를 채울 때 이 이름으로 찾는다 */
  id: string;
  /** 어떤 화면을 캡처해야 하는지 */
  description: string;
  caption?: string;
  media?: Media;
}

export type Visual = DiagramVisual | ImageVisual;

export interface Challenge {
  /** 과제 이름. 앞 번호는 화면에서 붙이므로 쓰지 않는다 */
  title: string;
  /** 무엇이 막혔는지 */
  problem: string;
  /** 문제를 다시 정의한 문장. 화면에서 굵게 표시한다 */
  definition?: string;
  /** 무엇을 골랐고 무엇을 버렸는지 */
  solution: string;
  /** 해결됐다는 것을 어떻게 확인했는지. 검증만 적는다 */
  verification?: string;
  /** 재지 못한 것과 남은 한계 */
  limitation?: string;
  /** 과제의 지표 행에 표시하는 성과 수치 */
  metric?: Metric;
  /** 선택 행 아래에 세로로 나열하는 도표·이미지 */
  visuals?: Visual[];
  /** 이 과제를 자세히 다룬 블로그 글 경로 */
  postHref?: string;
}

export interface Project {
  /** 포트폴리오 창의 가상 경로(project/<slug>)와 /portfolio?open=project/<slug> 링크에 쓰는 소문자 영문 식별자. 바꾸면 기존 링크가 깨진다 */
  slug: string;
  name: string;
  nameEn: string;
  /** 서비스 한 줄. 상세 페이지의 설명과 메타 description에 쓴다 */
  tagline: string;
  period: string;
  team: string;
  role: string;
  links: { github?: string; demo?: string };
  /** 대표 이미지. 목록 카드·OG 이미지·상세 소개에 쓴다 */
  cover: Media;
  /** 서비스, 담당 범위, 팀과의 경계를 담은 소개 한 문단 */
  intro: string;
  architecture: DiagramVisual;
  /** 직접 해결한 과제 */
  challenges: Challenge[];
  /** 회고. 없으면 회고 블록을 표시하지 않는다 */
  retrospective?: string;
  stack: string[];
}

export interface Education {
  name: string;
  org: string;
  period: string;
}

